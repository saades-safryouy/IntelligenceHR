export type EmployeeCopy = {
  [K in keyof typeof en]: string
}
export type EmployeeCopyKey = keyof EmployeeCopy

export function apiNotificationTitle(type: string, fallback: string, copy: EmployeeCopy): string {
  if (type === 'workflow.approval_required') return copy.notifWorkflowApprovalRequired
  if (type === 'workflow.updated') return copy.notifWorkflowUpdated
  if (type === 'workflow.approval_delegated') return copy.notifWorkflowDelegated
  return fallback
}

export function apiNotificationBody(type: string, fallback: string | null, copy: EmployeeCopy): string {
  if (type === 'workflow.approval_required') return copy.notifWorkflowApprovalRequiredBody
  if (type === 'workflow.updated') return copy.notifWorkflowUpdatedBody
  if (type === 'workflow.approval_delegated') return copy.notifWorkflowDelegatedBody
  return fallback ?? ''
}

